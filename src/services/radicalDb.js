export const EXPANDED_RADICALS_DATA = (() => {
  const expanded = [];
  RADICALS_DATA.forEach(r => {
    if (r.char.includes('(') && r.char.includes(')')) {
      const mainChar = r.char.split('(')[0].trim();
      const altChar = r.char.split('(')[1].replace(')', '').trim();
      
      expanded.push({
        ...r,
        id: r.id + '_main',
        char: mainChar,
        example: `${mainChar} (${r.fullMeaning})`
      });
      expanded.push({
        ...r,
        id: r.id + '_alt',
        char: altChar,
        example: `${altChar} (${r.fullMeaning})`
      });
    } else {
      expanded.push(r);
    }
  });
  return expanded;
})();

export function getRadicalsByStrokes(strokeCount) {
  if (strokeCount === 'all') return RADICALS_DATA;
  const num = parseInt(strokeCount, 10);
  return RADICALS_DATA.filter(r => r.strokes === num);
}

export function getCumulativeRadicalCards(strokeCount, limit = 30) {
  let pool = [];
  if (strokeCount === 'all') {
    pool = [...EXPANDED_RADICALS_DATA];
  } else {
    const maxStrokes = parseInt(strokeCount, 10);
    pool = EXPANDED_RADICALS_DATA.filter(r => r.strokes <= maxStrokes);
  }

  // Shuffling the pool using Fisher-Yates algorithm
  const shuffled = [...pool];
  for (let i = shuffled.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
  }

  return shuffled.slice(0, limit);
}
